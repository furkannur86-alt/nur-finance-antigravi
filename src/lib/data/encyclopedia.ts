export function searchEncyclopedia(query: string): EncyclopediaEntry[] {
  const q = query.toLowerCase();
  return encyclopediaEntries.filter(
    (e) =>
      e.term.toLowerCase().includes(q) ||
      e.shortDef.toLowerCase().includes(q) ||
      e.category.toLowerCase().includes(q) ||
      e.id.includes(q)
  );
}

export function getEntriesByCategory(category: string): EncyclopediaEntry[] {
  return encyclopediaEntries.filter((e) => e.category === category);
}

export function getEntryById(id: string): EncyclopediaEntry | undefined {
  return encyclopediaEntries.find((e) => e.id === id);
}
