export const translations: Record<string, TranslationSet> = { en, tr, de, ar, zh };

export function getTranslation(locale: Locale, section: keyof TranslationSet, key: string): string {
  const set = translations[locale] || translations.en;
  return set[section]?.[key] || translations.en[section]?.[key] || key;
}

export function t(locale: Locale, path: string): string {
  const [section, key] = path.split(".") as [keyof TranslationSet, string];
  return getTranslation(locale, section, key);
}
